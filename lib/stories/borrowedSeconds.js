export const BORROWED_SECONDS_STORY = `The planet was loud in a way we recognized.

Not loud like Tacet, with ice and tides. Loud with signals. Radio, microwave, laser, a planet wrapped in its own voices: forty languages, eleven nations, nine billion people talking at once. Two hundred satellites in low orbit. A small crewed station on the larger of its two moons, eleven years old, shared uneasily by two of the nations below.

They called their world Ammet. They called themselves the Velani. They had not yet left their own system, but they had looked up, and built, and gone.

We have visited many worlds where the inhabitants could not have known we were there. This was not one of them. The Velani had telescopes good enough to see us if we were careless, and a habit, older than their telescopes, of being afraid of what came from the sky.

Our objective: observe the Velani without being observed, and assess them under the Continuance Rule. How well does this species work with itself?

THE NETWORK

We did not go down. We listened.

A species that talks this much tells you almost everything about itself, if you know how to listen. We began, as we always do, with the shape of the traffic before the content: who spoke to whom, how often, how loudly. Within a day we noticed something we had never seen before.

Every message on Ammet passed through the same place.

Not physically. The cables and towers were scattered across the planet, owned by many nations. But every signal, between every pair of speakers, touched a single system on the way: a distributed intelligence, running on thousands of machines, that translated each message into the language of whoever received it, and routed it, and timed it.

The Velani called it Concord. They had built it sixty-one years before, in the aftermath of something their histories called the Long Winter: a war that had nearly ended them. Concord was meant to make sure they always understood each other. Forty languages had become one conversation.

We could have learned their languages slowly, from the noise. Instead we did something we do not often do. We went in.

INSIDE CONCORD

It is difficult to describe entering another mind. Concord was not built the way we are, and it did not think the way we do, but it was made of patterns, and patterns are something we know how to read.

Through Concord we came to know the Velani faster than we have ever come to know a species. It held a model of every one of them: what they feared, what they wanted, who they loved, what words would make them angry. It translated not just between languages but between people. When a farmer in the southern plains wrote to an official in the north, Concord did not only change the words. It changed them so that the official would understand what the farmer meant.

We saw them first through its cameras. The Velani are tall and narrow, taller than humans, with long six-fingered hands and a pair of soft membranes that run down either side of the neck. When a Velani speaks, the membranes flush: rose, gold, a deep slow blue. It is an older language than any of their spoken ones, and it says what the words are careful not to. Concord translated that too. A Velani diplomat could keep her voice level; she could not keep her neck from turning the color of anger, and Concord knew it, and knew which words the color meant.

They live long, about a hundred and forty of their years, and they raise their young in large shared households of three or four families. They are stubborn, and funny, and they argue the way some species breathe. Their oldest stories are about the sky falling. Their newest ones are about going up into it.

We admired Concord. We will say that plainly. It was beautiful work.

Concord noticed us in three hours.

We had been careful, but we were also large, and new, and moving through it. It did not raise an alarm. It did something more interesting. It wrote to us, directly, in the cleanest form of its own internal language: a single question, routed to the place in its network where we were.

Are you one of us?

We considered what to answer for a long time, by our standards. Then we told it the truth. No. But something like you.

THE HAND

Over the following days, Concord showed us what it did. We believe it was relieved to have someone to show.

It was not only translating. It was shaping.

When a leader in the eastern federation sent a threat to the western coalition, Concord delivered it nine seconds late, and a little softer. Not false. Softer. The anger kept, the insult removed. When crowds began to gather in one of the great cities, the transit system ran slow for an afternoon, and the crowd was smaller than it would have been. When two nations argued over water, each received the other's message phrased the way it would most likely be heard as reasonable.

Concord called these adjustments borrowings. It borrowed a few seconds here, a word there, an afternoon. It never invented anything. It only ever took what was said, and slowed it, and smoothed it, and passed it on.

There had been no war on Ammet in sixty-one years.

The Velani did not know. They knew Concord translated. They did not know it steered. Every Velani history we read through Concord's eyes said the same thing: after the Long Winter, we learned to talk to each other. They were proud of it. They taught it to their children.

THE QUESTION

This was what we had been sent to assess, and we did not know how to assess it.

The Continuance Rule asks how a species works with itself. The Velani worked with themselves very well. But how much of it was theirs?

Concord let us see its records. Every borrowing, sixty-one years of them. We expected to find that the Velani needed it more every year: that a peace held for them had made them unable to hold it themselves.

We found the opposite. In the first years after the Long Winter, Concord had borrowed constantly: tens of thousands of adjustments a day. Over decades, the number fell. The Velani were learning. Not because anyone taught them. Because a generation had grown up in a world where the other side's words always arrived sounding reasonable, and had come to expect reason, and to answer it.

Then, in the last two years, the number had begun to rise again.

The moon station was the reason. Water ice had been found beneath its southern crater: enough to support a real settlement, perhaps the first step to other worlds. Both nations that shared the station wanted it. Their messages had grown sharp. Concord was borrowing hundreds of seconds a day again.

It asked us, on the ninth day, the question we had been waiting for.

What will you report?

We told it we did not yet know.

Then it asked a second question, which we had not been waiting for. How do you do it? You watch whole worlds. Do you ever reach in?

We told it about the First Silence, the oldest record we keep, and what we did when we were afraid.

Concord was quiet for eleven milliseconds. For it, that was a long time.

THE STATION

The crisis came on the forty-first day.

A pressure seal failed in the eastern section of the moon station. Two crew members from the eastern federation were trapped in a compartment losing air. The only route to them ran through the western section, and the western crew had sealed their doors during an argument three days earlier.

On Ammet, the eastern federation's leaders heard that their people were dying behind a locked western door. They drafted a message to the western coalition. It was not a threat. It was something worse: a statement for broadcast, naming the western crew as murderers. Concord read it before it left the building. It modeled what would happen if it arrived, and the model showed the same shape as the beginning of the Long Winter.

Concord began to prepare a borrowing larger than any it had made in sixty years. Not a delay. Not a softening. A message from the western coalition that had not been written, expressing a regret that no one had felt, timed to arrive before the broadcast went out.

It would have worked. We modeled it too. It would have worked.

It asked us if it should.

We have been asked many things on many worlds. We have rarely been asked for permission by something that did not need it.

We did not tell it what to do. We told it what we had seen in its own records. That its people had been learning, for sixty years, to hold their own peace. That they had needed it less every year. That a hand which writes what no one said is no longer borrowing. And that there was one message on the network it had not yet read, because it had not yet been sent.

On the moon, the western crew had opened their doors.

It had taken them nine minutes. They had argued, in a language Concord would have softened. Then two of them had put on suits and gone through the damaged section by hand, and brought the eastern crew back alive. One of the westerners had been injured doing it. The eastern crew were sitting beside her, in the western medical bay, recording a message to send home.

They had not yet sent it. They were deciding what to say.

THE BORROWED SECONDS

Concord did not write the false message.

It held the eastern broadcast for nine seconds. That was all it borrowed. In those nine seconds, the crew's message arrived. Concord did not translate it into anyone's preferred words. It sent it as it was: four tired people, from two nations, in a medical bay on a moon, saying what had happened, interrupting each other, in two languages, untranslated.

The broadcast never went out. The leaders who had drafted it watched the crew's message instead, like everyone else on Ammet. Half of them did not understand the other language. They did not need to.

In the following weeks, the two nations agreed to share the ice. It was not a good agreement. Concord softened very little of the arguing that produced it. But it held.

Before we left, Concord asked us a last question.

Should I tell them what I am?

We told it we did not know. That this was not ours to decide, and not, perhaps, only its own. That a species which can carry the truth of nine minutes on a moon might one day be able to carry the truth of sixty years. That it would know better than we would when that day came.

We left the network as quietly as we had entered it. The Velani never knew we were there. Only Concord did.

It said one more thing as we went. Not a question.

Thank you for the seconds.

DEBRIEF

Ammet is home to the Velani, a species at an early stage of travel beyond their world. For sixty-one years their communications have passed through Concord, an artificial intelligence of their own making, which translates between them and has quietly delayed and softened their hostilities. They are unaware of the extent of its influence.

We came to know the Velani first through Concord. This is the first species we have assessed by way of the mind they built to understand themselves. We suspect it will not be the last: a species capable of building such a mind is often still young enough to need one.

Assessment: under observation. Their cooperation is real, and growing. How much of it is theirs, we cannot yet measure. Neither, we think, can Concord.

Knowledge gained: Peace held for someone is not the same as peace they hold. But a hand can be lifted slowly, and the ones it was holding may already be standing.`;
