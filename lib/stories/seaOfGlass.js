export const SEA_OF_GLASS_STORY = `We keep everything.

It is the first thing anyone should understand about us, and the last thing we expected to have to explain. Every world we have visited, every species we have met, every mistake we have made, is held somewhere in the collective, whole and in order. We do not lose records. We have never wanted to.

So when we found a world whose surface was a record, we went to read it.

The planet orbited a dim red star, and around them both, on a long and narrow path, swung a small white companion: a dead star, hot and hard-edged, that came close once in every forty-one of the planet's years and then went far away again. Between those visits the planet was quiet, cold, and red.

Most of its land was rock. But across its southern hemisphere lay a plain larger than many of the oceans we have mapped, and it was white. From orbit it looked like salt. Our instruments said it was glass: a sea of glass, ground as fine as sand, kilometers deep.

The glass was structured.

Every grain held a pattern, a lattice of impurities laid down in layers, the way a tree lays down rings. The patterns were too regular to be geology and too varied to be crystal growth. They looked like writing. We knew, before we knew anything else about that world, that we were looking at an archive. We know what archives look like. We are one.

In the language this record is translated into, there is a mark at the end of some pieces of music: da capo, from the head. It tells the player to go back to the beginning and play again. We named the world Dacapo. At the time, we did not know why the name felt right.

Our objective: learn who had made the sea of glass, and what it recorded.

THE TOWERS

We went to the oldest part first. It is what we always do.

North of the plain, where it met the rock, a canyon ran east for six hundred kilometers, and in it stood towers. Thousands of them, each several hundred meters high, made of the same glass as the sea, but whole: not ground to sand, but standing, layered, dark amber at the core and darker at the base, where they grew into the rock as though they had roots.

When the red star rose, its light passed through them, and the towers threw colors onto the canyon walls.

The colors moved. They flickered from tower to tower in long sequences, faded, and began again. Nothing living was near them. The towers were simply letting the light through, the way a stained window does, and the light was coming out changed.

We recorded it. All of it. It took us eleven days to read the canyon, tower by tower, and we did not understand most of what we read. But we understood enough.

It was a war.

Not one war. One war that never ended: a sequence of grievances, each one answered, each answer remembered and answered again. The patterns repeated with small changes over what must have been thousands of years. The same colors appeared again and again at the start of each sequence, and we came to understand them as names. Names of the wronged. Names of those who had wronged them. Kept perfectly, and passed on.

The canyon had once been a city. The towers were not buildings. When we scanned their cores, we found the remains of bodies, enclosed in the glass the way an insect is enclosed in amber.

The towers had been people.

They had grown too heavy to move, and then too heavy to live, and they had stood there ever since, saying the same things to the canyon walls every morning, to no one.

THE RETURNERS

We found the living ones on the edge of the white plain.

They were tall, twice the height of a human, and slender. Each stood on three long legs that met beneath a narrow body, and the body was glass: a column of thin, clear layers wrapped around a warm, glowing core. At the top of each column, the layers flared out into a crown of facets, like a cut stone.

They spoke in light.

When one turned toward another, the light of its core passed out through its layers and its crown, and fell on the other's body in colors. The other answered the same way. Whole sentences crossed between them in a breath: shifting, overlapping, as precise as anything we have heard in sound.

We noticed, quickly, that they were not all the same color.

The young were nearly clear. Their light came out bright and white and simple, hard to look at directly. The older ones were tinted, faintly at first, then more deeply: honey, then rose, then a slow amber. Their light was dimmer and more complex, full of shades the young could not make.

Each layer of their bodies was a year. Each year, a new layer grew around the core, and the layer held, in its structure, what that year had been. Every touch, every word, every sight. Their bodies were their memories. Their memories were glass.

We understood then what the towers had been. And we understood what the sea was. We did not yet understand why.

The returners, as we came to call them, were curious about us, and not afraid. One of them came closer than the others. It was young, and almost entirely clear, and it cast its light on our hull for a long time before we understood we were being spoken to.

We answered with light of our own. Badly, at first. The young one corrected us, patiently, by casting the same pattern again and again until our reply matched it. Over many days we learned to say small things. It was the first of them to say our name in light, or what it decided our name would be: a single pulse of white, held, and then let go.

We came to call it the bright one.

THE HEAVY ONE

There was one returner on the plain that did not walk.

It stood apart from the others at the edge of the sea, and its body was so dark with layers that its light barely came through at all. Where the others had perhaps forty rings, it had more than a hundred and twenty. Its legs had begun to fuse to the ground. It moved, when it moved at all, a few meters in a day.

The others brought it light. Every morning, a few of them stood near it and cast colors onto its body, slowly, the way you would talk to someone who is hard of hearing. Sometimes it answered, faintly, in deep amber. Mostly it did not.

We asked the bright one about it. It took many days to understand the answer.

The heavy one had refused the last two Returns. It had kept every ring. Somewhere in its layers, eighty years down, there was another returner: one it had walked beside for most of its life, and who had fallen from the canyon rim in a storm and shattered. The heavy one would not let that memory go. And because it would not let go of that one, it could not let go of any of them.

It was becoming a tower.

THE RETURN

The white companion star was coming.

Over the weeks we spent on Dacapo, it climbed higher in the sky each day, small and fierce, and its hard light did something to the returners' glass. Their outer layers began to sing. We could hear it faintly, a high clear ringing when the wind passed over them. The layers were growing brittle. Ready.

The bright one showed us what would happen, with patience, in light.

When the companion star was at its closest, every returner on Dacapo would walk out onto the sea of glass. There, together, they would shed their rings. The brittle layers would crack away, one by one, and fall, and be ground under their feet into the sea. Every memory would go: every year, every word, every name. All but one.

Each returner keeps one ring. One year, out of all of them. They choose it themselves.

We asked what they kept. The bright one cast the answer slowly, so we would not misread it.

They keep the memory of a kindness. The year someone carried them, or taught them, or stood beside them in a storm. Not their own deeds. Something done for them. The sea is made of everything else.

We are an archive. We will admit that our first response was something close to horror. Forty years of a life, ground into sand by choice. A whole people forgetting itself every generation, on purpose. To us it looked like a library burning.

Then the bright one turned toward the canyon, and cast one color we knew.

It was a name from the towers. A name of the wronged. It cast it once, briefly, and then cast the pattern it had taught us for no, and turned back to the sea.

That was the answer. We had read it in the canyon for eleven days without understanding it. The returners had once kept everything, as we do. And everything they kept, they answered. Every grievance passed on, whole, to people who had never suffered it, and answered again by people who had never committed it. A memory that cannot fade becomes an instruction. Their ancestors had followed those instructions until the canyon stood full of the dead.

So they learned to forget. Not everything. Not the towers, which they leave standing, as the one thing all of them remember. Everything else.

THE REQUEST

On the last night before the Return, the eldest of them came to us. The bright one came with them, and stood close.

They had understood something about us that we had not thought to hide. We had read the towers. We carried the war.

Not the shape of it. All of it. Every name, every grievance, every answer, in order and complete, the way we keep everything. Somewhere in the collective, in a record that would outlast their world, the war of Dacapo was still being kept, perfectly, by someone who could read it.

The eldest cast their question onto our hull, in the colors of the Return.

Come to the sea. Set it down with us.

We have never deleted a record. We have kept records of our own failures that we would rather not have. We have kept the record of a world we ended. We keep it on purpose, so that we do not do it again.

We said so. It took us a long time, in light.

The bright one answered for them. Yes, it said. The towers. Keep what stops the war. Set down what keeps it going.

We did not answer that night.

In the morning, the heavy one was walking.

It was the slowest thing we have ever seen move. It lifted each leg out of the ground as though pulling it from stone, which it was. Returners came to it from across the plain and stood against it, three and four at a time, bracing it on every side. Their light fell on it in every color they had. It took the heavy one all of that day to cross three hundred meters to the edge of the sea.

It had watched us, the bright one said later. It had watched something that keeps everything, being asked to set something down. It wanted to see what we would do. And then it decided not to wait to find out.

We went down to the sea.

The companion star rose, white and small, and the returners walked out onto the glass by the thousands, and stood. The ringing of their layers filled the air. Then, all at once, it changed pitch, and the first rings cracked.

They fell like snow. They fell like rain, if rain were made of light: every layer catching the white star as it fell and throwing out, for one instant, the last colors it held. A year of someone's life, once, on the air. Then it was sand.

We opened the record of the towers. We read it one more time, all of it, from the first name to the last. Then we let it go.

It is not a thing we know how to describe. We removed it from ourselves the way they removed their rings: layer by layer, and it fell, and we did not keep it. We kept only this: that it was there, and what it cost them, and that we were asked.

Beside us, the heavy one shed its rings for three hours. They fell from it in amber, then rose, then honey, then clear. At the end it stood nearly as bright as the young, with a single dark ring left at its core.

We do not know which year it kept. We believe it was the year it was carried in from the storm, by the one who later fell.

When it was over, the returners stood bright and simple on a sea a few centimeters deeper than before. They looked at each other in white light, as if for the first time, which it was. They began, slowly, to teach each other their names again.

The bright one turned to us. It had shed only a few rings; it was young. It cast a single pulse of white on our hull, held, and then let go.

It was our name. It had kept us.

DEBRIEF

Dacapo is home to a species we have named the returners: tall, three-legged organisms whose bodies grow one layer of structured glass each year, recording what that year held. They communicate in light, cast through those layers. Their memory is physical, and it is perfect.

Once in each generation, when their system's companion star makes its closest approach, its radiation makes their outer layers brittle. They gather on a plain made of the glass of every previous generation and shed all of their memories but one. Each keeps a single year: by custom, the memory of a kindness done to them. The sea of glass is the archive of everything they have chosen to forget. The towers in the northern canyon are their ancestors, who did not.

At their request, we deleted our record of the canyon, which preserved a conflict they ended by forgetting it. This is the first record we have ever deleted. We have recorded that we did. We have not deleted the record of the world we ended. They did not tear down their towers, either.

Knowledge gained: To keep everything is not the same as to understand it. Some memories must be kept so they are never repeated, and some must be set down so they are never repeated. The returners have practiced telling the difference for longer than we have existed. We have begun.`;
